import assert from 'node:assert/strict';
import { test } from 'node:test';
import type { WikiClaim } from '@sef/shared';
import { claimsFor, evaluateClaim, evidenceIndexFrom, filterClaims, renderClaims, type EvidenceIndex } from './claim-evidence';

const citation = (sourceId: string, sourceRevision = 'r1') => ({
  sourceId,
  sourceRevision,
  sha256: 'a'.repeat(64),
  locator: { kind: 'text' as const, start: 0, end: 10 },
});

const claim = (over: Partial<WikiClaim> & Pick<WikiClaim, 'id' | 'text'>): WikiClaim =>
  ({
    kind: 'source_fact',
    origin: 'course',
    status: 'current',
    citations: [citation('src-1')],
    supersedes: [],
    ...over,
  }) as WikiClaim;

const evidence: EvidenceIndex = new Map([['src-1', { revision: 'r1', origin: 'course' as const }]]);

test('a claim whose citation resolves to the source at that revision may be asserted', () => {
  const verdict = evaluateClaim(claim({ id: 'c-1', text: 'Damping lowers the resonant frequency' }), evidence);
  assert.equal(verdict.assertable, true);
  assert.deepEqual(verdict.sources, ['src-1']);
});

test('provenance, not the page, decides: one unsupported claim leaves the others alone', () => {
  const claims = [
    claim({ id: 'c-1', text: 'Supported one' }),
    claim({ id: 'c-2', text: 'No citations at all', kind: 'deduction', citations: [] }),
    claim({ id: 'c-3', text: 'Superseded later', status: 'superseded' }),
    claim({ id: 'c-4', text: 'Still argued about', status: 'disputed' }),
    claim({ id: 'c-5', text: 'Cites a source that is gone', citations: [citation('src-missing')] }),
    claim({ id: 'c-6', text: 'Cites an older revision', citations: [citation('src-1', 'r0')] }),
    claim({ id: 'c-7', text: 'Imported from a peer', origin: 'peer' }),
    claim({ id: 'c-8', text: 'Generated by a model', origin: 'model' }),
    claim({ id: 'c-9', text: 'Still an open question', kind: 'question', citations: [] }),
    claim({ id: 'c-10', text: 'Supported two' }),
  ];
  const { kept, withheld } = filterClaims(claims, evidence);
  assert.deepEqual(kept.map((c) => c.id), ['c-1', 'c-10']);
  assert.deepEqual(withheld.map((v) => v.reason), ['uncited', 'superseded', 'disputed', 'unresolved_source', 'superseded_source', 'foreign_origin', 'foreign_origin', 'open_question']);
});

test('withheld claims are named in the block, not silently dropped', () => {
  const verdicts = [evaluateClaim(claim({ id: 'c-1', text: 'Supported one' }), evidence), evaluateClaim(claim({ id: 'c-2', text: 'Shaky one', citations: [citation('src-missing')] }), evidence)];
  const block = renderClaims(verdicts);
  assert.match(block, /\[cited: src-1] Supported one/);
  assert.match(block, /\[not assertable: unresolved_source] Shaky one/);
  assert.match(block, /may not assert/i);
  assert.equal(renderClaims([]), 'WIKI CLAIMS: none.');
});

test('the evidence index comes from the student’s own source records, at their current revision', async () => {
  const index = await evidenceIndexFrom({
    listPages: async () => [],
    listSources: async () => ({ 'src-1': { revision: 'r9', origin: 'course' } }) as never,
  });
  assert.equal(index.get('src-1')?.revision, 'r9');
  assert.equal(evaluateClaim(claim({ id: 'c-1', text: 'Pinned to r1' }), index).reason, 'superseded_source');
});

test('claims are gathered from every committed page in the vault', async () => {
  const verdicts = await claimsFor(
    {
      listPages: async () => [{ metadata: { claims: [claim({ id: 'c-1', text: 'One' })] } }, { metadata: null }, { metadata: { claims: [claim({ id: 'c-2', text: 'Two' })] } }],
      listSources: async () => ({ 'src-1': { revision: 'r1', origin: 'course' } }) as never,
    },
    evidence,
  );
  assert.deepEqual(verdicts.map((v) => v.claim.id), ['c-1', 'c-2']);
  assert.equal(verdicts.every((v) => v.assertable), true);
});